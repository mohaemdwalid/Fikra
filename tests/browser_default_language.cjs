const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const base = process.env.PREVIEW_URL || 'http://127.0.0.1:5184/';
(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  for (const width of [390, 1440]) {
    const context = await browser.newContext({ viewport: { width, height: 1000 } });
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    await page.goto(new URL('/?utm_source=instagram#faq', base).href);
    await page.waitForURL('**/ar/?utm_source=instagram#faq');
    assert.equal(await page.locator('html').getAttribute('lang'), 'ar');
    assert.equal(await page.locator('html').getAttribute('dir'), 'rtl');
    await page.locator('.fikra-language').click();
    await page.waitForURL('**/?utm_source=instagram&lang=en#faq');
    assert.equal(await page.locator('html').getAttribute('lang'), 'en');
    await page.reload();
    assert.equal(await page.locator('html').getAttribute('lang'), 'en');
    await page.goto(base);
    assert.equal(await page.locator('html').getAttribute('lang'), 'en');
    await page.locator('#home [data-fikra-booking]').click();
    await page.waitForURL('**/book/**');
    await page.waitForFunction(() => window.FIKRA_I18N);
    assert.equal(await page.locator('html').getAttribute('lang'), 'en');
    await page.locator('.fikra-language').click();
    assert.equal(await page.locator('html').getAttribute('lang'), 'ar');
    await page.reload();
    await page.waitForFunction(() => window.FIKRA_I18N);
    assert.equal(await page.locator('html').getAttribute('lang'), 'ar');
    assert.deepEqual(errors, []);
    await context.close();
    const fresh = await browser.newPage({ viewport: { width, height: 1100 } });
    await fresh.goto(new URL('/book/', base).href);
    await fresh.waitForFunction(() => window.FIKRA_I18N);
    assert.equal(await fresh.locator('html').getAttribute('lang'), 'ar');
    assert.equal(await fresh.locator('html').getAttribute('dir'), 'rtl');
    assert.deepEqual(await fresh.locator('[name=product_count]').evaluateAll(inputs => inputs.map(i => i.value)), ['Under 25', '25 to 100', '100 to 500', 'More than 500']);
    const options = await fresh.locator('.booking-product-choices').innerText();
    for (const copy of ['أقل من ٢٥', 'من ٢٥ إلى ١٠٠', 'من ١٠٠ إلى ٥٠٠', 'أكثر من ٥٠٠']) assert.ok(options.includes(copy));
    await fresh.screenshot({ path: `/tmp/fikra-four-products-ar-${width}.png`, fullPage: true });
    await fresh.close();
    console.log(width, 'Arabic defaults, English preference, campaign/hash preservation and four translated options PASS');
  }
  const noScript = await browser.newPage({ javaScriptEnabled: false });
  await noScript.goto(base);
  await noScript.waitForURL('**/ar/');
  assert.equal(await noScript.locator('html').getAttribute('lang'), 'ar');
  await noScript.close();
  await browser.close();
})().catch(e => { console.error(e); process.exit(1); });
